// GiST Exclude Conflict Checker
// Verifies if [startTime, endTime) overlaps with any existing shift for the same employee on the same date
export const checkShiftConflict = (
  shifts: StaffShift[],
  currentShiftId: string | null,
  userId: string,
  date: string,
  startTime: string,
  endTime: string
): ConflictCheckResult => {
  const timeToMinutes = (t: string) => {
    const [h, m] = t.split(":").map(Number);
    return h * 60 + m;
  };

  const newStart = timeToMinutes(startTime);
  const newEnd = timeToMinutes(endTime);

  if (newStart >= newEnd) {
    return {
      hasConflict: true,
      message: "Giờ bắt đầu phải nhỏ hơn giờ kết thúc",
    };
  }

  const conflictingShift = shifts.find((s) => {
    if (s.status === "CANCELLED") return false;
    if (currentShiftId && s.id === currentShiftId) return false;
    if (s.userId !== userId || s.date !== date) return false;

    const existingStart = timeToMinutes(s.startTime);
    const existingEnd = timeToMinutes(s.endTime);

    // Overlap condition: max(start1, start2) < min(end1, end2)
    return Math.max(newStart, existingStart) < Math.min(newEnd, existingEnd);
  });

  if (conflictingShift) {
    return {
      hasConflict: true,
      conflictingShift,
      message: `Cảnh báo GiST Exclude: Nhân viên đã có ca trực trùng giờ (${conflictingShift.startTime} - ${conflictingShift.endTime}) vào ngày này.`,
    };
  }

  return { hasConflict: false };
};
