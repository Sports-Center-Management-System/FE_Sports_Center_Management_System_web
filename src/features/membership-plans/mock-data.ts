// Trigger DB barrier validator
export const validateCurriculumRequirements = (
  discipline: DisciplineType,
  groupClassQuota: number
): TriggerValidationResult => {
  if (discipline === "GYM" && groupClassQuota > 0) {
    return {
      isBlocked: true,
      triggerName: "trg_check_gym_curriculum_no_group_class",
      message:
        "Vi phạm quy tắc cấu trúc gói (Trigger DB Chặn): Bộ môn Gym chỉ hỗ trợ vé tự do và PT 1:1, không áp dụng hình thức lớp nhóm (groupClassQuota phải bằng 0).",
    };
  }

  return { isBlocked: false };
};
